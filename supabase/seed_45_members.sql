          '00000000-0000-0000-0000-000000000000',
          -- Pure-SQL UUID generator so we don't need pgcrypto's
          -- gen_random_uuid(). Same RFC 4122 v4 format as gen_random_uuid().
          (
            substring(md5(random()::text || clock_timestamp()::text) for 8) || '-' ||
            substring(md5(random()::text || clock_timestamp()::text) for 4) || '-4' ||
            substring(substring(md5(random()::text) for 12) for 1) ||
            substring(substring(md5(random()::text) for 12) for 2) || '-' ||
            substring('89ab', 1 + (abs(hashtext(random()::text)) % 4)::int, 1) ||
            substring(md5(random()::text) for 3) || '-' ||
            substring(md5(random()::text) for 12)
          )::uuid,
          'authenticated',
          'authenticated',
          v_email,
          v_pw_hash,
          now(),
          jsonb_build_object('provider','email','providers', array['email']),
          jsonb_build_object(
            'service_number',  v_svc,
            'full_name',       v_orig,
            'rank',            v_member->>'rank'
          ),
          now(),
          now(),
          '',
          '',
          '',
          ''
        )
        returning id into v_auth_id;
      exception when others then
        v_failed := v_failed + 1;
        v_report := v_report || jsonb_build_array(jsonb_build_object(
          'service_number', v_svc,
          'email',         v_email,
          'status',        'failed',
          'user_id',       null,
          'message',       sqlerrm
        ));
        raise notice 'seed failed svc=% email=% err=%', v_svc, v_email, sqlerrm;
        return continue;  -- next iteration
      end;

      -- Insert public.users (explicit; doesn't depend on the trigger).
      begin
        insert into public.users (
          auth_id, service_number, full_name, email, role_id, rank,
          is_active
        ) values (
          v_auth_id, v_svc, v_orig, v_email, v_role_id, v_member->>'rank',
          true
        )
        returning id into v_user_id;
      exception when others then
        v_failed := v_failed + 1;
        v_report := v_report || jsonb_build_array(jsonb_build_object(
          'service_number', v_svc,
          'email',         v_email,
          'status',        'failed_public_users',
          'user_id',       null,
          'message',       sqlerrm
        ));
        -- Best-effort cleanup of the auth row.
        delete from auth.users where id = v_auth_id;
        raise notice 'seed failed_public_users svc=% email=% err=%', v_svc, v_email, sqlerrm;
        return continue;
      end;

      -- Insert public.members.
      begin
        insert into public.members (
          user_id, service_number, first_name, last_name, rank
        ) values (
          v_user_id, v_svc, v_first, v_last, v_member->>'rank'
        );
      exception when others then
        -- Soft-fail: keep public.users, just log the failure on the members row.
        v_report := v_report || jsonb_build_array(jsonb_build_object(
          'service_number', v_svc,
          'email',         v_email,
          'status',        'failed_members',
          'user_id',       v_user_id,
          'message',       'public.users ok, public.members failed: ' || sqlerrm
        ));
        v_failed := v_failed + 1;
        raise notice 'seed failed_members svc=% email=% err=%', v_svc, v_email, sqlerrm;
        return continue;
      end;

      v_seed := v_seed + 1;
      v_report := v_report || jsonb_build_array(jsonb_build_object(
        'service_number', v_svc,
        'email',         v_email,
        'status',        'seeded',
        'user_id',       v_user_id,
        'message',       'ok'
      ));
    end row;
  end loop;

  -- 4. Summary.
  raise notice '================================================================';
  raise notice '  MMMIS bulk member seed — done';
  raise notice '  total = %, seeded = %, skipped = %, failed = %',
               v_count, v_seed, v_skipped, v_failed;
  raise notice '  temp password = %', v_temp_pw;
  raise notice '================================================================';

  -- 5. Results table (visible in the SQL Editor "Results" panel).
  create temp table if not exists _seed_results (
    service_number text,
    email          text,
    status         text,
    user_id        uuid,
    message        text
  ) on commit drop;
  execute 'truncate table _seed_results';
  insert into _seed_results
  select
    (r->>'service_number')::text,
    (r->>'email')::text,
    (r->>'status')::text,
    nullif(r->>'user_id','')::uuid,
    r->>'message'
  from jsonb_array_elements(v_report) r;
end $$;

-- 6. Show the grid.
