-- =============================================================================
-- Seed 45 mess members — single-shot SQL
--
-- Run the entire file in the Supabase SQL Editor. No migrations to apply,
-- no Edge Function to deploy, no CSV to upload, no extension required.
-- The script:
--
--   1. Uses a pre-computed bcrypt cost-10 hash of the temporary password
--      ("Welcome123!"). The hash is pasted in as a literal so this script
--      does not depend on pgcrypto being installed in the SQL Editor's
--      search path (some Supabase projects don't have it).
--   2. INSERTs one row into auth.users per member with:
--        - email                = '<service_no>@<email_dom>'   (placeholder)
--        - email_confirmed_at   = now()                         (no confirmation link)
--        - encrypted_password   = bcrypt('Welcome123!')
--        - raw_user_meta_data   = { service_number, full_name, rank }
--   3. Immediately INSERTs the matching public.users + public.members rows
--      (does NOT rely on the AFTER INSERT trigger from migration 0015).
--   4. Prints a results grid in the editor: service_number, email, status,
--      user_id, message.
--
-- Idempotency:
--   - Rows whose service_number already exists in public.users (active) are
--     skipped — they appear in the report as 'skipped_active'.
--   - Re-running the script does not duplicate anything.
--
-- Members sign in at /login with:
--   service_number : e.g. 5083
--   password       : Welcome123!
-- They can change their password from /portal/profile after signing in.
-- They can set their real email later from /portal/profile (or via the
-- set-member-email Edge Function — optional).
-- =============================================================================

set search_path = public;

-- Pre-computed bcrypt cost-10 hash of 'Welcome123!'. We use this literal
-- instead of calling pgcrypto's crypt() at runtime, because some Supabase
-- projects don't have pgcrypto installed in the SQL Editor's search path.
-- gotrue accepts both $2a$ and $2b$ prefixes for verification, so this is
-- equivalent to what createUser() would produce.
--
-- Generated by: node -e "console.log(require('bcryptjs').hashSync('Welcome123!', 10))"
-- If you change v_temp_pw below, regenerate the hash with the same call and
-- paste it as v_pw_hash.
do $$
declare
  v_temp_pw   text    := 'Welcome123!';     -- edit if you want a different temp password
  v_pw_hash   text    := '$2b$10$yhukt3/f2KbmKEdApw4I8OyUdifFOHNoX9ObH5chD8iY3NlhPzpN.';
  v_email_dom text    := 'mmmis.vercel.app';    -- edit if your mess uses a different domain
  v_role_id   smallint;
  v_svc       text;
  v_email     text;
  v_auth_id   uuid;
  v_user_id   uuid;
  v_existing  uuid;
  v_count     integer := 0;
  v_seed      integer := 0;
  v_skipped   integer := 0;
  v_failed    integer := 0;

  -- The 45 members. (svc, rank, name) — corrected set per the admin.
  v_members constant jsonb := '[
