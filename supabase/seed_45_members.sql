    {"svc":"003678", "rank":"CE",     "name":"MR PHIRI A"}
  ]'::jsonb;

  v_member   jsonb;
  v_report   jsonb := '[]'::jsonb;
  v_orig     text;   -- full_name as supplied (kept verbatim in public.users)
  v_norm     text;   -- salutation-stripped, used for the first/last split
  v_first    text;
  v_last     text;
  v_sal_pos  integer;
begin
  -- 1. Member role id.
  select id into v_role_id from public.roles where code = 'member';
  if v_role_id is null then
    raise exception 'member role missing from public.roles (run 0001_init.sql first)';
  end if;

  -- 2. Bcrypt hash is pre-computed at the top of this block (v_pw_hash).
  --    We do NOT call pgcrypto here because the SQL Editor role may not
  --    have it on its search_path. The pre-computed $2b$10$... literal is
  --    equivalent to what auth.admin.createUser() would have produced.

  -- 3. Loop.
  for v_member in
    select * from jsonb_array_elements(v_members)
  loop
    v_svc    := v_member->>'svc';
    v_email  := ltrim(v_svc, '0') || '@' || v_email_dom;
    v_count  := v_count + 1;

    -- Skip if an active row already exists for this service_number.
    select id into v_user_id
      from public.users
     where service_number = v_svc
       and deleted_at is null
     limit 1;
    if v_user_id is not null then
      v_skipped := v_skipped + 1;
      v_report := v_report || jsonb_build_array(jsonb_build_object(
        'service_number', v_svc,
        'email',         v_email,
        'status',        'skipped_active',
        'user_id',       v_user_id,
        'message',       'public.users row already exists and is not deleted'
      ));
      continue;
    end if;

    -- Name split. We preserve the full string in `full_name` (the column
    -- that gets shown in the UI). For first_name / last_name we use a
    -- simple convention that matches the data shape:
    --   - Strip a leading salutation token (MR / MRS / MS / DR) if present.
    --   - first_name = first token of the remainder
    --   - last_name  = the rest of the tokens joined
    -- For military-roster entries ("MUPEKA C", "MWANSA K") this puts the
    -- surname in first_name and the initials in last_name. For Western-
    -- order entries ("H M KABONDE") it puts the first initial in first_name
    -- and the remainder in last_name. Either way the full_name column
    -- keeps the original spelling, and members can correct the split from
    -- /portal/profile if they need to.
    v_orig := coalesce(v_member->>'name', '');
    v_norm := btrim(regexp_replace(v_orig, '\s+', ' ', 'g'));
    v_sal_pos := case
      when v_norm ~* '^(MR|MRS|MS|DR)\s+' then 1
      else 0
    end;
    if v_sal_pos = 1 then
      v_norm := substring(v_norm from position(' ' in v_norm) + 1);
    end if;
    if position(' ' in v_norm) > 0 then
      v_first := split_part(v_norm, ' ', 1);
      v_last  := substring(v_norm from position(' ' in v_norm) + 1);
    else
      v_first := v_norm;
      v_last  := '';
    end if;

    -- Savepoint so a per-row failure doesn't roll back the whole batch.
    -- (The whole do $$ block is one transaction; we need SAVEPOINTs to
    -- isolate individual failures.)
    <<row>> begin
      -- Insert auth.users.
      begin
        insert into auth.users (
          instance_id,
          id,
          aud,
          role,
          email,
          encrypted_password,
          email_confirmed_at,
          raw_app_meta_data,
          raw_user_meta_data,
          created_at,
          updated_at,
          confirmation_token,
          email_change,
          email_change_token_new,
          recovery_token
